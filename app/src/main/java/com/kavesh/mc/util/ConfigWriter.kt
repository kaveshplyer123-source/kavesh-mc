package com.kavesh.mc.util

import com.kavesh.mc.model.ServerConfig
import java.io.File

object ConfigWriter {
    /**
     * Generates real PumpkinMC configuration.toml, features.toml, and standard server.properties
     * inside the server directory before launching the native binary.
     */
    fun writeServerFiles(serverDir: File, config: ServerConfig) {
        serverDir.mkdirs()
        val configDir = File(serverDir, "config").apply { mkdirs() }
        File(serverDir, "world").mkdirs()
        File(serverDir, "plugins").mkdirs()

        // 1. eula.txt
        File(serverDir, "eula.txt").writeText("eula=${config.eulaAccepted}
")

        // 2. PumpkinMC configuration.toml
        val pumpkinToml = """
            # Generated by Kavesh-MC
            server_address = "0.0.0.0:${config.port}"
            max_players = ${config.performance.maxPlayers}
            view_distance = ${config.performance.viewDistance}
            simulation_distance = ${config.performance.simulationDistance}
            default_difficulty = "${config.gameplay.difficulty}"
            online_mode = ${config.onlineMode}
            allow_chat_reports = false
            motd = "${config.motd.replace(""", "'")}"
            tps = 20.0
            spawn_protection = ${config.gameplay.spawnProtection}
            use_console = true
            console_color = false
            
            [resource_pack]
            enabled = ${config.gameplay.resourcePackUrl.isNotBlank()}
            resource_pack_url = "${config.gameplay.resourcePackUrl}"
            force = false
        """.trimIndent()
        File(configDir, "configuration.toml").writeText(pumpkinToml)

        // 3. Standard server.properties (for Paper/Vanilla compatibility)
        val properties = """
            # Kavesh-MC Server Properties
            server-port=${config.port}
            max-players=${config.performance.maxPlayers}
            view-distance=${config.performance.viewDistance}
            simulation-distance=${config.performance.simulationDistance}
            gamemode=${config.gameplay.gamemode.lowercase()}
            difficulty=${config.gameplay.difficulty.lowercase()}
            hardcore=${config.gameplay.hardcore}
            online-mode=${config.onlineMode}
            spawn-protection=${config.gameplay.spawnProtection}
            enable-command-block=${config.gameplay.commandBlocks}
            level-seed=${config.seed}
            motd=${config.motd}
            resource-pack=${config.gameplay.resourcePackUrl}
        """.trimIndent()
        File(serverDir, "server.properties").writeText(properties)
    }
}
